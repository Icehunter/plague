col_inputs = {row[0]: row[1:] for row in T_COLOR_INPUTS}


def colour_model(p, frame, vdots, alt_raw):
    ea, et, n0, na, nr, d0, dn = p
    anchor_n, anchor_d, night_f, noon_f, sv2, rain = col_inputs[frame]
    inv_n = max(1.0 - night_f, 0.0)
    day_w = inv_n ** (ea + (et - ea) * (0.5 + 0.5 * vdots))
    alt4 = (alt_raw * alt_raw) ** 2
    nm = n0 * (1.0 - na * alt4) * (1.0 - nr * rain)
    n_col = np.array(anchor_n) * nm
    d_col = np.array(anchor_d) * (d0 + dn * noon_f)
    return n_col * (1.0 - day_w) + d_col * day_w


col_targets = [(f, v, a, np.array(rgb)) for f, v, a, rgb in T_COLOR]


def colour_cost(p):
    e = 0.0
    for f, v, a, rgb in col_targets:
        e += float(((colour_model(p, f, v, a) - rgb) ** 2).sum())
    return e


rng = np.random.default_rng(8)
lo = np.array([0.05, 0.05, 0.3, 0.0, 0.0, 0.2, 0.0])
hi = np.array([12.0, 12.0, 4.0, 1.0, 1.0, 1.6, 1.2])
cand = [(colour_cost(p), tuple(p)) for p in (lo + (hi - lo) * rng.random((8000, 7)))]
cand.sort(key=lambda t: t[0])
pool = [np.array(p) for _, p in cand[:8]]
best_c = (cand[0][1], cand[0][0])
for p in pool:
    step = (hi - lo) * 0.08
    cur, cur_c = p.copy(), colour_cost(p)
    for _ in range(160):
        moved = False
        for i in range(7):
            for sgn in (1.0, -1.0):
                trial = cur.copy()
                trial[i] = float(np.clip(trial[i] + sgn * step[i], lo[i], hi[i]))
                tc = colour_cost(trial)
                if tc < cur_c:
                    cur, cur_c, moved = trial, tc, True
        if not moved:
            step *= 0.5
            if step.max() < 1e-4:
                break
    if cur_c < best_c[1]:
        best_c = (tuple(cur), cur_c)

COL_P = best_c[0]
