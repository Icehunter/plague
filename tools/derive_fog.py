# Slider map: cubic in log space for both parameters. The fitted pairs span nearly a decade
# in `a` with visible curvature; lower orders bow off the endpoints, and the default reach
# sits between knots where that bow is the whole error.
LOGA = np.polyfit(r_arr2, [math.log(border_fits[r][0]) for r in reaches], 3)
LOGB = np.polyfit(r_arr2, [math.log(border_fits[r][1]) for r in reaches], 3)


def border_model(x, reach):
    a = math.exp(np.polyval(LOGA, reach))
    b = math.exp(np.polyval(LOGB, reach))
    return kumaraswamy(x, a, b)


