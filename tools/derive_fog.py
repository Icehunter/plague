# =================================================================================================
# The model: reference implementation. The shader mirrors these forms; this file owns the fits.
# =================================================================================================

RD_REF = 192.0    # vanilla's DEFAULT render distance: 12 chunks * 16 blocks. Not tuned; cited.
MIN_RD = 32.0     # render-distance floor, carried from the pack's own prior code (ours).
SEA_LEVEL = 63.0  # vanilla sea level.


def ren_factor(rd):
    """Optical depth scales by min(RD_REF/rd, 1): constant world-unit haze past the reference,
    no compensation below it."""
    return min(RD_REF / max(rd, MIN_RD), 1.0)


def op_air(d, lam, k, rd):
    """Weibull extinction opacity in distance."""
    d = np.asarray(d, dtype=np.float64)
    return 1.0 - np.exp(-((d / lam) ** k) * ren_factor(rd))


def w_endpoint(y, H):
    return np.exp(-np.maximum(np.asarray(y, dtype=np.float64) - SEA_LEVEL, 0.0) / H)


def w_pathmean(ya, yb, H):
    """Mean of w(y) over a straight path from altitude ya to yb, closed form, piecewise at
    sea level where the profile saturates."""
    lo, hi = (ya, yb) if ya <= yb else (yb, ya)
    if hi - lo < 1e-9:
        return float(w_endpoint(0.5 * (lo + hi), H))
    total = hi - lo
    below = min(max(SEA_LEVEL - lo, 0.0), total)          # saturated stretch: weight 1
    acc = below
    y1 = max(lo, SEA_LEVEL)
    if hi > y1:
        acc += H * (math.exp(-(y1 - SEA_LEVEL) / H) - math.exp(-(hi - SEA_LEVEL) / H))
    return acc / total


def alt_weight(cam, frag, rain, H, floor, lift, rise):
    """DENSER of the fragment's own weight and the path mean (a slant ray can't avoid its low,
    dense segment). The climb factor RISES as the eye exits the layer: the prior build read haze
    as denser from outside than from within (up to ~1.39x from a high camera); rain removes the
    distinction. Exactly 1.0 at sea level, so ground tables and S(rain) stay untangled from it."""
    Hr = H * (1.0 + lift * rain)
    w = max(float(w_endpoint(frag, Hr)), w_pathmean(cam, frag, Hr))
    climb = 1.0 - float(w_endpoint(cam, Hr))
    return (floor + (1.0 - floor) * w) * (1.0 + rise * climb * (1.0 - rain))


def kumaraswamy(x, a, b):
    x = np.clip(np.asarray(x, dtype=np.float64), 0.0, 1.0)
    return 1.0 - (1.0 - x ** a) ** b



# =================================================================================================
# Fit 1+2: distance curve and damping cap, one joint fit per rain state, all render distances
# =================================================================================================

def fit_weibull_joint(rows):
    """rows: (rd, d, opacity). tau = (d/lam)^k * renFactor(rd); opacity = S * (1 - exp(-tau)).
    Alternates a log-log regression for (k, lam) with a linear least-squares step for S. The
    ren factor rides INSIDE the regression, so every render distance conditions the same fit."""
    rd = np.array([r[0] for r in rows])
    d = np.array([r[1] for r in rows])
    op = np.array([r[2] for r in rows])
    renf = np.array([ren_factor(v) for v in rd])
    k, lam = 3.0, 100.0
    S = max(float(op.max()), 1e-3)
    for _ in range(80):
        y = np.clip(op / S, 0.0, 0.9999)
        m = (y > 1e-7) & (y < 0.99)
        t = np.log(-np.log(1.0 - y[m])) - np.log(renf[m])
        X = np.log(d[m])
        A = np.stack([X, np.ones_like(X)], axis=1)
        coef, *_ = np.linalg.lstsq(A, t, rcond=None)
        k = float(coef[0])
        lam = float(math.exp(-coef[1] / k))
        f = 1.0 - np.exp(-((d / lam) ** k) * renf)
        S = float((op * f).sum() / (f * f).sum())
    resid = float(np.abs(op - S * (1.0 - np.exp(-((d / lam) ** k) * renf))).max())
    return k, lam, S, resid


