border_groups = {}
for reach, x, op in T_BORDER:
    border_groups.setdefault(reach, []).append((x, op))


def fit_kumaraswamy(rows):
    x = np.array([r[0] for r in rows])
    op = np.array([r[1] for r in rows])
    # Toe-weighted: an error of 0.02 where the prior curve is still dark tints half the view;
    # the same error at 80% opacity moves nothing anyone can see.
    wt = 1.0 + 4.0 * np.exp(-op * 30.0)
    best = (None, math.inf)
    a_grid = np.exp(np.linspace(math.log(0.8), math.log(64.0), 44))
    b_grid = np.exp(np.linspace(math.log(0.4), math.log(16.0), 40))
    for a in a_grid:
        for b in b_grid:
            r = float((wt * (kumaraswamy(x, a, b) - op) ** 2).sum())
            if r < best[1]:
                best = ((a, b), r)
    for _ in range(3):
        (a0, b0), _ = best
        for a in np.linspace(a0 * 0.8, a0 * 1.25, 15):
            for b in np.linspace(b0 * 0.8, b0 * 1.25, 15):
                r = float((wt * (kumaraswamy(x, a, b) - op) ** 2).sum())
                if r < best[1]:
                    best = ((a, b), r)
    (a, b), _ = best
    resid = float(np.abs(kumaraswamy(x, a, b) - op).max())
    return a, b, resid


border_fits = {}
for reach, rows in sorted(border_groups.items()):
    border_fits[reach] = fit_kumaraswamy(rows)

reaches = sorted(border_fits)
